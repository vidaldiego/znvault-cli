import { afterEach, describe, expect, it } from 'vitest';
import { mkdtempSync, cpSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { spawnSync } from 'node:child_process';
const root = resolve(import.meta.dirname, '../..');
const dirs: string[] = [];
const temp = () => { const path = mkdtempSync(join(tmpdir(), 'recovery-sync-')); dirs.push(path); return path; };
afterEach(() => dirs.splice(0).forEach(path => rmSync(path, { recursive: true, force: true })));
// Catches accepting altered generated sources/provenance and requiring Archon at build time.
describe('pinned generated recovery snapshot', () => {
  it('checks committed bytes without another repository and rejects changed generated source', () => {
    const copy = temp(); cpSync(join(root, 'src/vendor/archon-recovery-core'), join(copy, 'src/vendor/archon-recovery-core'), { recursive: true });
    const run = () => spawnSync(process.execPath, [join(root, 'scripts/sync-archon-recovery.mjs'), '--check', '--root', copy], { encoding: 'utf8' });
    expect(run().status).toBe(0);
    const path = join(copy, 'src/vendor/archon-recovery-core/selection.ts'); writeFileSync(path, readFileSync(path, 'utf8') + '\n// changed');
    expect(run().status).not.toBe(0);
  });
  it('refuses wrong source provenance before creating or overwriting a snapshot', () => {
    const source = temp(); writeFileSync(join(source, 'PROVENANCE.json'), JSON.stringify({ sourceSha: 'f70d4df95d002ef022fa514b498cc121527e4242', files: [] }));
    const result = spawnSync(process.execPath, [join(root, 'scripts/sync-archon-recovery.mjs'), '--source', source, '--root', temp()], { encoding: 'utf8' });
    expect(result.status).not.toBe(0); expect(result.stderr).toMatch(/provenance/);
  });
});

it('adapts actual import/export specifiers while leaving data, comments and unrelated modules intact', async () => {
  const { adaptModuleSpecifiers } = await import('../../scripts/sync-archon-recovery.mjs');
  const source = `import type { T } from './types';\nexport * from "./selection";\nimport fs from 'node:fs';\nconst text = "from './data'";\n// export * from './comment';\n`;
  const expected = `import type { T } from './types.js';\nexport * from "./selection.js";\nimport fs from 'node:fs';\nconst text = "from './data'";\n// export * from './comment';\n`;
  expect(adaptModuleSpecifiers(source)).toBe(expected);
  expect(adaptModuleSpecifiers(expected, true)).toBe(source);
});

it('generates only pinned sources and rejects altered export bytes before writing', async () => {
  const { adaptModuleSpecifiers } = await import('../../scripts/sync-archon-recovery.mjs');
  const source = temp(); const output = temp();
  const vendor = join(root, 'src/vendor/archon-recovery-core');
  const provenance = JSON.parse(readFileSync(join(vendor, 'SOURCE-PROVENANCE.json'), 'utf8'));
  writeFileSync(join(source, 'PROVENANCE.json'), readFileSync(join(vendor, 'SOURCE-PROVENANCE.json')));
  const prefix = '/* eslint-disable */\n// GENERATED by scripts/sync-archon-recovery.mjs; edit the maintained Archon source.\n';
  for (const file of provenance.files) writeFileSync(join(source, file.path), adaptModuleSpecifiers(readFileSync(join(vendor, file.path), 'utf8').slice(prefix.length), true));
  writeFileSync(join(source, 'forbidden-fixture.test.ts'), 'must not ship');
  const run = () => spawnSync(process.execPath, [join(root, 'scripts/sync-archon-recovery.mjs'), '--source', source, '--root', output], { encoding: 'utf8' });
  expect(run().status).toBe(0);
  const check = spawnSync(process.execPath, [join(root, 'scripts/sync-archon-recovery.mjs'), '--check', '--root', output], { encoding: 'utf8' });
  expect(check.status, check.stderr).toBe(0);
  writeFileSync(join(source, 'selection.ts'), '// unreviewed source');
  const failed = run(); expect(failed.status).not.toBe(0); expect(failed.stderr).toMatch(/source bytes mismatch/);
  expect(readFileSync(join(output, 'src/vendor/archon-recovery-core/selection.ts')).equals(readFileSync(join(vendor, 'selection.ts')))).toBe(true);
});
