#!/usr/bin/env node
// Explicit import from the independently exported, reviewed Archon commit.
import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir, readdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const sourceSha = '6eb993b48dc315179809cffa555aed6ed952dd87';
const exportDigest = 'ff678e526a090b177f2753d538d643d57e660fd6821da931807690200c011e34';
const names = ['arcn-envelope.ts', 'arcn-format.ts', 'arcn-stream.ts', 'companion.ts', 'index.ts', 'json.ts', 'selection.ts', 'types.ts'];
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const prefix = '/* eslint-disable */\n// GENERATED by scripts/sync-archon-recovery.mjs; edit the maintained Archon source.\n';
// Transformation v1: actual import/export module specifiers only, including types.
export function adaptModuleSpecifiers(text, reverse = false) {
  const ast = ts.createSourceFile('recovery.ts', text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const edits = [];
  for (const statement of ast.statements) {
    if (!ts.isImportDeclaration(statement) && !ts.isExportDeclaration(statement)) continue;
    const specifier = statement.moduleSpecifier;
    if (!specifier || !ts.isStringLiteral(specifier) || !specifier.text.startsWith('./')) continue;
    const value = reverse ? specifier.text.replace(/\.js$/, '') : specifier.text + '.js';
    edits.push({ start: specifier.getStart(ast) + 1, end: specifier.getEnd() - 1, value });
  }
  for (const edit of edits.reverse()) text = text.slice(0, edit.start) + edit.value + text.slice(edit.end);
  return text;
}
const transform = bytes => Buffer.from(prefix + adaptModuleSpecifiers(bytes.toString('utf8')));
async function main() {
  const args = process.argv.slice(2); let root = resolve(fileURLToPath(new URL('..', import.meta.url))); let source; let check = false;
  while (args.length) { const arg = args.shift(); if (arg === '--check') check = true; else if (arg === '--root' && args.length) root = resolve(args.shift()); else if (arg === '--source' && args.length) source = resolve(args.shift()); else throw Error('usage: sync-archon-recovery.mjs --source EXPORT_DIRECTORY | --check [--root CLI_ROOT]'); }
  if (check === Boolean(source)) throw Error('select exactly one of --source or --check');
  const output = join(root, 'src/vendor/archon-recovery-core');
  const original = await readFile(join(source ?? output, source ? 'PROVENANCE.json' : 'SOURCE-PROVENANCE.json'));
  if (digest(original) !== exportDigest) throw Error('source provenance does not match the pinned reviewed export');
  const provenance = JSON.parse(original);
  if (provenance.sourceSha !== sourceSha || JSON.stringify(provenance.files.map(f => f.path)) !== JSON.stringify(names)) throw Error('source provenance allowlist mismatch');
  const generated = [];
  for (const file of provenance.files) {
    const bytes = await readFile(join(source ?? output, file.path));
    let adapted;
    if (source) { if (bytes.length !== file.bytes || digest(bytes) !== file.sha256) throw Error(`source bytes mismatch: ${file.path}`); adapted = transform(bytes); }
    else {
      // Recover exact upstream bytes only through the documented deterministic adaptation.
      const upstream = Buffer.from(adaptModuleSpecifiers(bytes.toString('utf8').slice(prefix.length), true));
      if (upstream.length !== file.bytes || digest(upstream) !== file.sha256 || !transform(upstream).equals(bytes)) throw Error(`generated bytes mismatch: ${file.path}`);
      adapted = bytes;
    }
    generated.push({ ...file, generatedSha256: digest(adapted), generatedBytes: adapted.length, bytes: adapted });
  }
  const record = { format: 'znvault-archon-recovery-snapshot-v1', sourceSha, exportSha256: exportDigest, transformationVersion: 1, adaptation: 'eslint-disable header and AST import/export relative ESM .js suffixes only', files: generated.map(({ bytes, ...file }) => file) };
  const compiled = '// GENERATED by scripts/sync-archon-recovery.mjs\nexport const recoveryCoreProvenance = ' + JSON.stringify(record, null, 2) + ' as const;\n';
  if (check) {
    if ((await readFile(join(output, 'provenance.ts'), 'utf8')) !== compiled) throw Error('generated provenance mismatch');
    const actual = (await readdir(output)).sort(); const expected = [...names, 'SOURCE-PROVENANCE.json', 'provenance.ts'].sort();
    if (JSON.stringify(actual) !== JSON.stringify(expected)) throw Error('unexpected generated file (fixtures/tests are forbidden)');
  } else {
    // All source validation precedes any write. No implicit checkout lookup.
    await mkdir(output, { recursive: true });
    for (const file of generated) await writeFile(join(output, file.path), file.bytes);
    await writeFile(join(output, 'SOURCE-PROVENANCE.json'), original); await writeFile(join(output, 'provenance.ts'), compiled);
  }
  console.log(`${check ? 'Checked' : 'Synchronized'} 8 recovery sources from ${sourceSha}`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main().catch(error => { console.error(error.message); process.exitCode = 1; });
